"""Generate imagery on the exact Sentinel-2 UTM grid.

Run `python generate_plots.py`. Downloaded zoom-18 Esri tiles are reused from
.tile-cache; the legacy tiles/plots directory is deliberately untouched.
"""
import argparse
import io
import json
import math
from pathlib import Path
import time

import numpy as np
from PIL import Image
from pyproj import Transformer
from rasterio.enums import Resampling
from rasterio.transform import Affine
from rasterio.warp import reproject
import requests

ROOT = Path(__file__).resolve().parent
ZOOM = 18
TILE_SIZE = 256
MERCATOR_HALF = math.pi * 6378137
TILE_SPAN = 2 * MERCATOR_HALF / (2 ** ZOOM)
OUTPUT_SIZE = 1000
OUTPUT_RESOLUTION = 0.5
ESRI_URL = 'https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/tile/{z}/{y}/{x}'


def reproject_plot(source, source_transform, plot, resampling=Resampling.bilinear):
    """Warp band-first EPSG:3857 data onto a 500m north-up UTM square."""
    destination = np.zeros((source.shape[0], OUTPUT_SIZE, OUTPUT_SIZE), dtype=source.dtype)
    transform = Affine(OUTPUT_RESOLUTION, 0, plot['utmX0'], 0,
                       -OUTPUT_RESOLUTION, plot['utmY0'])
    reproject(source=source, destination=destination,
              src_transform=source_transform, src_crs='EPSG:3857',
              dst_transform=transform, dst_crs='EPSG:32651',
              resampling=resampling)
    return destination


def metadata_source(grid, plots):
    records = [dict(plot, tilePath=f"tiles/s2-plots/plot_{plot['idx']:03d}.jpg?v=s2-v1") for plot in plots]
    return ('// Generated by generate_plots.py; do not edit.\n'
            f'window.GRID = {json.dumps(grid, indent=2)};\n'
            f'window.PLOTS = {json.dumps(records, indent=2)};\n')


class TileCache:
    """Validated on-disk tile cache with a four-request-per-second ceiling."""
    def __init__(self, directory, interval=0.25):
        self.directory = Path(directory) / str(ZOOM)
        self.directory.mkdir(parents=True, exist_ok=True)
        self.interval = interval
        self.last_request = 0
        self.downloaded = 0
        self.session = requests.Session()
        self.session.headers['User-Agent'] = 'Thesis-Digimap/1.0 (non-commercial crop-labeling research; one-time UTM imagery generation)'

    def get(self, x, y):
        path = self.directory / f'{y}_{x}.jpg'
        if path.exists():
            try:
                with Image.open(path) as image:
                    if image.size == (TILE_SIZE, TILE_SIZE):
                        return np.asarray(image.convert('RGB')).copy()
            except (OSError, ValueError):
                pass
        for attempt in range(4):
            time.sleep(max(0, self.interval - (time.monotonic() - self.last_request)))
            self.last_request = time.monotonic()
            try:
                response = self.session.get(ESRI_URL.format(z=ZOOM, x=x, y=y), timeout=30)
                response.raise_for_status()
                with Image.open(io.BytesIO(response.content)) as image:
                    if image.size != (TILE_SIZE, TILE_SIZE):
                        raise ValueError(f'Unexpected Esri tile dimensions: {image.size}')
                    pixels = np.asarray(image.convert('RGB')).copy()
                path.write_bytes(response.content)
                self.downloaded += 1
                return pixels
            except (requests.RequestException, OSError, ValueError):
                if attempt == 3:
                    raise
                time.sleep(2 ** attempt)

    def close(self):
        self.session.close()


def mosaic_for_plot(plot, cache):
    transform = Transformer.from_crs(32651, 3857, always_xy=True)
    # An extra source pixel footprint protects bilinear interpolation at edges.
    points = [transform.transform(x, y)
              for x in (plot['utmX0'] - 2, plot['utmX0'] + 502)
              for y in (plot['utmY0'] - 502, plot['utmY0'] + 2)]
    minx, maxx = min(p[0] for p in points), max(p[0] for p in points)
    miny, maxy = min(p[1] for p in points), max(p[1] for p in points)
    left = math.floor((minx + MERCATOR_HALF) / TILE_SPAN)
    right = math.floor((maxx + MERCATOR_HALF) / TILE_SPAN)
    top = math.floor((MERCATOR_HALF - maxy) / TILE_SPAN)
    bottom = math.floor((MERCATOR_HALF - miny) / TILE_SPAN)
    mosaic = np.zeros(((bottom - top + 1) * TILE_SIZE,
                       (right - left + 1) * TILE_SIZE, 3), dtype=np.uint8)
    for y in range(top, bottom + 1):
        for x in range(left, right + 1):
            row, col = (y - top) * TILE_SIZE, (x - left) * TILE_SIZE
            mosaic[row:row + TILE_SIZE, col:col + TILE_SIZE] = cache.get(x, y)
    pixel_size = TILE_SPAN / TILE_SIZE
    source_transform = Affine(pixel_size, 0, -MERCATOR_HALF + left * TILE_SPAN,
                              0, -pixel_size, MERCATOR_HALF - top * TILE_SPAN)
    return np.moveaxis(mosaic, 2, 0), source_transform


def main():
    from plot_grid import build_plots, grid_constants
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--force', action='store_true', help='regenerate existing images using cached source tiles')
    args = parser.parse_args()
    plots = build_plots()
    output = ROOT / 'tiles' / 's2-plots'
    output.mkdir(parents=True, exist_ok=True)
    (ROOT / 's2-grid-data.js').write_text(metadata_source(grid_constants(), plots), encoding='utf-8')
    cache = TileCache(ROOT / '.tile-cache')
    started = time.monotonic()
    try:
        for plot in plots:
            target = output / f"plot_{plot['idx']:03d}.jpg"
            if target.exists() and not args.force:
                with Image.open(target) as existing:
                    if existing.size == (OUTPUT_SIZE, OUTPUT_SIZE):
                        print(f"{plot['idx'] + 1}/{len(plots)} cached {target.name}", flush=True)
                        continue
            source, transform = mosaic_for_plot(plot, cache)
            image = Image.fromarray(np.moveaxis(reproject_plot(source, transform, plot), 0, 2))
            image.save(target, quality=80)
            print(f"{plot['idx'] + 1}/{len(plots)} rendered {target.name}; {cache.downloaded} new tiles; {time.monotonic() - started:.0f}s", flush=True)
    finally:
        cache.close()


if __name__ == '__main__':
    main()
